// ---- Helpers --------------------------------------------------------------
export const formatINR = (value) =>
  '₹' + Number(value).toLocaleString('en-IN')

export const getProduct = (id) => products.find((p) => p.id === id)

export const productsByCategory = (slug) =>
  products.filter((p) => p.category === slug)

export const featuredProducts = products.filter((p) =>
  p.tags.includes('featured'),
)
export const newArrivals = products.filter((p) =>
  p.tags.includes('new-arrival'),
)
export const bestSellers = products.filter((p) =>
  p.tags.includes('bestseller'),
)

export const discountPercent = (p) =>
  p.oldPrice ? Math.round((1 - p.price / p.oldPrice) * 100) : 0
